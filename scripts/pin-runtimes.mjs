/** Explicit developer audit step; never run on installation or automatically. */
import { readdir, readFile, writeFile, lstat } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { join, relative } from 'node:path';
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const pins = {};
for (const [folder, kind] of [['code-host', 'code-host'], ['wasi', 'wasi'], ['rules', 'trusted-ifeval']]) {
  const root = join('resources/runtime', folder), files = [];
  async function walk(path) {
    const stat = await lstat(path);
    if (stat.isSymbolicLink()) throw new Error('Links cannot be pinned');
    if (stat.isDirectory()) for (const name of (await readdir(path)).sort()) await walk(join(path, name));
    else if (stat.isFile() && path !== join(root, 'runtime.json')) files.push({ path: relative(root, path).replaceAll('\\', '/'), sha256: hash(await readFile(path)) });
  }
  await walk(root);
  files.sort((a, b) => a.path < b.path ? -1 : a.path > b.path ? 1 : 0);
  const raw = JSON.stringify({ schemaVersion: 1, kind, files }, null, 2) + '\n';
  await writeFile(join(root, 'runtime.json'), raw);
  pins[kind] = hash(raw);
}
await writeFile('src/runtime/pins.ts', '/** Generated by explicit developer audit; compiled into Host code. */\nexport const RUNTIME_PINS = ' + JSON.stringify(pins, null, 2) + ' as const;\n');
process.stdout.write(JSON.stringify(pins) + '\n');
